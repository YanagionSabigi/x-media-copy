const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
// Chrome deduplicates a content-script URL across MAIN/ISOLATED injection in
// some builds. Give MAIN a standalone entry containing its own parser.
fs.writeFileSync(path.join(root, 'media-main.js'), '// Generated by scripts/vendor.cjs from media.js + media-hook.js.\n' +
  fs.readFileSync(path.join(root, 'media.js'), 'utf8') + '\n' + fs.readFileSync(path.join(root, 'media-hook.js'), 'utf8'));
for (const [source, target] of [['@ffmpeg/ffmpeg/dist/esm', 'vendor/ffmpeg'], ['@ffmpeg/core/dist/esm', 'vendor/core']]) {
  const src = path.join(root, 'node_modules', source), dst = path.join(root, target);
  fs.mkdirSync(dst, { recursive: true });
  for (const name of fs.readdirSync(src)) if (/\.(js|wasm)$/.test(name)) fs.copyFileSync(path.join(src, name), path.join(dst, name));
}
// Eliminate the upstream CDN fallback: all execution must use packaged assets.
const constants = path.join(root, 'vendor/ffmpeg/const.js');
fs.writeFileSync(constants, fs.readFileSync(constants, 'utf8').replace(/export const CORE_URL = .*?;/, 'export const CORE_URL = new URL("../core/ffmpeg-core.js", import.meta.url).href;'));
console.log('Bundled local FFmpeg JS, worker and single-thread WASM.');
