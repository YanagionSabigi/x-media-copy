const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
test('MAIN media entry bundles its parser and cannot become stale or share an isolated script URL', () => {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json')));
  const main = manifest.content_scripts.find(script => script.world === 'MAIN');
  assert.deepEqual(main.js, ['media-main.js']);
  const isolated = manifest.content_scripts.filter(script => script.world !== 'MAIN').flatMap(script => script.js);
  assert.equal(isolated.includes('media-main.js'), false);
  const expected = '// Generated by scripts/vendor.cjs from media.js + media-hook.js.\n' + fs.readFileSync(path.join(root, 'media.js'), 'utf8') + '\n' + fs.readFileSync(path.join(root, 'media-hook.js'), 'utf8');
  assert.equal(fs.readFileSync(path.join(root, 'media-main.js'), 'utf8'), expected);
});
test('offline converter assets, licenses and narrow permissions are present', () => {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json')));
  assert.equal(manifest.version, require('../package.json').version);
  assert.deepEqual(manifest.host_permissions, ['https://pbs.twimg.com/*', 'https://video.twimg.com/*']);
  assert.equal(manifest.permissions.includes('nativeMessaging'), false);
  for (const file of ['offscreen.html', 'offscreen.js', 'vendor/core/ffmpeg-core.wasm', 'vendor/ffmpeg/worker.js', 'vendor/licenses/FFMPEG-WASM-MIT.txt', 'vendor/licenses/GPL-2.0.txt']) assert.ok(fs.statSync(path.join(root, file)).size > 100);
  assert.doesNotMatch(fs.readFileSync(path.join(root, 'vendor/ffmpeg/const.js'), 'utf8'), /https?:\/\//);
});
